#!/usr/bin/env python3
"""Generate a native, versioned libc shim for the guest's Bionic version nodes.

Source of truth: analysis/rea/bionic-versions.json (lead, task #374).
Output: src/compat/bionic_libc.c + src/compat/bionic_libc.map (task #373).

This is our own Linux code forwarding to glibc via dlopen("libc.so.6") — not a
translation layer. Function symbols are register-preserving x86-64 SysV
tail-call trampolines; data symbols are native variables seeded from glibc.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
data = json.loads((ROOT / "analysis/rea/bionic-versions.json").read_text())
symbols = data["symbols"]
# Keep only valid C identifiers; anything exotic gets a safe fallback name.
def cident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)

funcs = [s for s in symbols if re.match(r"^[A-Za-z_]\w*$", s["name"])]
# Type info from the guest dynsym: recover FUNC vs OBJECT from libroblox-imports.txt
import subprocess
guest = "/tmp/opencode/sober-apk/split/lib/x86_64/libroblox.so"
kind = {}
try:
    out = subprocess.run(["readelf", "--dyn-syms", "-W", guest],
                         capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        m = re.search(r"UND\s+([A-Za-z_]\w*)@", line)
        if m:
            parts = line.split()
            if len(parts) > 4:
                kind[m.group(1)] = parts[3]
except Exception:
    pass

funcs = [s for s in symbols if kind.get(s["name"], "FUNC") == "FUNC"]
objs = [s for s in symbols if kind.get(s["name"], "FUNC") == "OBJECT"]

lines = []
lines.append("/* GENERATED by src/compat/gen_bionic_libc.py — do not edit by hand. */")
lines.append('/* Native Linux libc shim with Bionic version nodes (task #373). */')
lines.append("#define _GNU_SOURCE")
lines.append("#include <dlfcn.h>")
lines.append("#include <stdio.h>")
lines.append("#include <stdlib.h>")
lines.append("#include <string.h>")
lines.append("")
lines.append("static void *g_glibc;")
lines.append("")
# DECISION 009: this DSO exports its own dlsym/dlopen/memcpy trampolines, so
# calls to those names from this file bind to THIS DSO's (still-NULL) trampoline
# slots -- the classic self-hosting bug. Resolve the real glibc functions with
# dlvsym(RTLD_DEFAULT, ...) instead: dlvsym is NOT exported by this DSO, so the
# call reaches the dynamic linker's genuine implementation.
lines.append("static void *(*real_dlsym_fn)(void *, const char *);")
lines.append("static void *(*real_dlopen_fn)(const char *, int);")
lines.append("static long (*real_sysconf_fn)(int);")
lines.append("")
lines.append("static void init_real_resolver(void)")
lines.append("{")
lines.append("    if (!real_dlsym_fn) {")
lines.append('        real_dlsym_fn = (void *(*)(void *, const char *))')
lines.append('            dlvsym(RTLD_DEFAULT, "dlsym", "GLIBC_2.34");')
lines.append("        if (!real_dlsym_fn)")
lines.append('            real_dlsym_fn = (void *(*)(void *, const char *))')
lines.append('                dlvsym(RTLD_DEFAULT, "dlsym", "GLIBC_2.2.5");')
lines.append("    }")
lines.append("    if (!real_dlopen_fn)")
lines.append('        real_dlopen_fn = (void *(*)(const char *, int))')
lines.append('            dlvsym(RTLD_DEFAULT, "dlopen", "GLIBC_2.34");')
lines.append("}")
lines.append("")
lines.append("static void *native_lookup(const char *name)")
lines.append("{")
lines.append("    init_real_resolver();")
lines.append("    void *h = g_glibc ? g_glibc : RTLD_DEFAULT;")
lines.append("    return real_dlsym_fn ? real_dlsym_fn(h, name) : NULL;")
lines.append("}")
lines.append("")
# The guest is a Bionic ELF: key 0x27 is Bionic's _SC_PAGESIZE. glibc uses 30
# for the same key, so forwarding 0x27 verbatim returns the CPU count (or 0),
# which makes the guest's arena size/alignment math degenerate (decision 009).
lines.append("static long sober_native_sysconf(int name)")
lines.append("{")
lines.append("    if (name == 0x27 || name == 30) return 4096;  /* Bionic/glibc _SC_PAGESIZE */")
lines.append("    if (name == 0x1e) return 4096;                 /* _SC_PAGE_SIZE */")
lines.append("    return real_sysconf_fn ? real_sysconf_fn(name) : 0;")
lines.append("}")
lines.append("")
for s in funcs:
    n = cident(s["name"])
    lines.append(f"void *sober_libc_fn_{n};")
lines.append("")
for s in objs:
    n = cident(s["name"])
    # __sF must cover Bionic's FILE __sF[3] (0x198 bytes): the guest derives
    # stdout/stderr as __sF+0x98 / __sF+0x130.
    obj_size = "0x200" if n == "__sF" else "64"
    lines.append(f"unsigned char sober_libc_obj_{n}[{obj_size}];")
lines.append("")

lines.append("#define TRAMP(name) \\")
lines.append("    __asm__ volatile ( \\")
lines.append('        ".globl " #name "\\n\\t" \\')
lines.append('        ".type " #name ", @function\\n\\t" \\')
lines.append('        #name ":\\n\\t" \\')
lines.append('        "movq sober_libc_fn_" #name "(%%rip), %%rax\\n\\t" \\')
lines.append('        "testq %%rax, %%rax\\n\\t" \\')
lines.append('        "jz 1f\\n\\t" \\')
lines.append('        "jmp *%%rax\\n\\t" \\')
lines.append('        "1: xorl %%eax, %%eax\\n\\t" \\')
lines.append('        "ret\\n\\t" \\')
lines.append('        ".size " #name ", .-" #name "\\n\\t" \\')
lines.append("        : : : \"memory\")")
lines.append("")

# Bionic stdio: __sF[3] uses a Bionic FILE layout (stride 0x98), so a guest
# fflush() on those objects must be mapped to the host streams.  glibc's
# fflush would interpret the Bionic struct as a glibc FILE and crash.
lines.append("/* Bionic stdio stream translation (__sF stride 0x98). */")
lines.append("static FILE *sober_host_stdin, *sober_host_stdout, *sober_host_stderr;")
lines.append("static FILE *sober_stdio_map(FILE *stream)")
lines.append("{")
lines.append("    unsigned char *p = (unsigned char *)stream;")
lines.append("    unsigned char *base = sober_libc_obj___sF;")
lines.append("    if (!p) return NULL;")
lines.append("    if (p >= base && p < base + sizeof(sober_libc_obj___sF)) {")
lines.append("        size_t off = (size_t)(p - base);")
lines.append("        if (off < 0x98) return sober_host_stdin;")
lines.append("        if (off < 0x130) return sober_host_stdout;")
lines.append("        return sober_host_stderr;")
lines.append("    }")
lines.append("    return stream;")
lines.append("}")
lines.append("")
lines.append("__attribute__((visibility(\"default\")))")
lines.append("int fflush(FILE *stream)")
lines.append("{")
lines.append("    typedef int (*sober_fflush_fn)(FILE *);")
lines.append("    sober_fflush_fn real = (sober_fflush_fn)sober_libc_fn_fflush;")
lines.append("    FILE *mapped = sober_stdio_map(stream);")
lines.append("    const char *dbg = getenv(\"SOBER_STDIO_DEBUG\");")
lines.append("    if (dbg && dbg[0] != '0' && sober_host_stderr)")
lines.append("        fprintf(sober_host_stderr,")
lines.append("                \"[stdio] fflush(%p) -> %p off=%ld\\n\",")
lines.append("                (void *)stream, (void *)mapped,")
lines.append("                (long)((unsigned char *)stream - sober_libc_obj___sF));")
lines.append("    return real ? real(mapped) : 0;")
lines.append("}")
lines.append("")
lines.append("__attribute__((visibility(\"default\")))")
lines.append("int fclose(FILE *stream)")
lines.append("{")
lines.append("    typedef int (*sober_fclose_fn)(FILE *);")
lines.append("    sober_fclose_fn real = (sober_fclose_fn)sober_libc_fn_fclose;")
lines.append("    const char *dbg = getenv(\"SOBER_STDIO_DEBUG\");")
lines.append("    if (dbg && dbg[0] != '0' && sober_host_stderr)")
lines.append("        fprintf(sober_host_stderr, \"[stdio] fclose(%p) off=%ld\\n\",")
lines.append("                (void *)stream,")
lines.append("                (long)((unsigned char *)stream - sober_libc_obj___sF));")
lines.append("    /* Never close a host standard stream through a Bionic FILE*. */")
lines.append("    if (sober_stdio_map(stream) != stream) return 0;")
lines.append("    /* Bionic tolerates repeated fclose on the same handle; glibc aborts. */")
lines.append("    static FILE *sober_closed[64]; static unsigned sober_nclosed;")
lines.append("    for (unsigned i = 0; i < sober_nclosed; ++i)")
lines.append("        if (sober_closed[i] == stream) return 0;")
lines.append("    if (sober_nclosed < 64) sober_closed[sober_nclosed++] = stream;")
lines.append("    return real ? real(stream) : 0;")
lines.append("}")
lines.append("")
lines.append("__attribute__((visibility(\"default\")))")
lines.append("size_t fwrite(const void *buf, size_t size, size_t n, FILE *stream)")
lines.append("{")
lines.append("    typedef size_t (*sober_fwrite_fn)(const void *, size_t, size_t, FILE *);")
lines.append("    sober_fwrite_fn real = (sober_fwrite_fn)sober_libc_fn_fwrite;")
lines.append("    FILE *mapped = sober_stdio_map(stream);")
lines.append("    const char *dbg = getenv(\"SOBER_STDIO_DEBUG\");")
lines.append("    if (dbg && dbg[0] != '0' && sober_host_stderr)")
lines.append("        fprintf(sober_host_stderr,")
lines.append("                \"[stdio] fwrite(%p,size=%zu,n=%zu,stream=%p) -> %p\\n\",")
lines.append("                buf, size, n, (void *)stream, (void *)mapped);")
lines.append("    return real ? real(buf, size, n, mapped) : 0;")
lines.append("}")
lines.append("")
lines.append("")
lines.append("")

# Bionic-compatible pthread TSD (decision 013): the guest allocates small
# integer keys and expects its own TSD array.  glibc's key space is unrelated
# and returned the stack-guard sentinel for the guest's key 2, so implement a
# private thread-local array here instead of forwarding these two symbols.
lines.append("/* Bionic-compatible pthread TSD (decision 013). */")
lines.append("#define SOBER_BIONIC_TSD_SLOTS 512")
lines.append("static _Thread_local void *sober_bionic_tsd[SOBER_BIONIC_TSD_SLOTS];")
lines.append("")
lines.append("__attribute__((visibility(\"default\")))")
lines.append("int pthread_setspecific(unsigned int key, const void *value)")
lines.append("{")
lines.append("    if (key >= SOBER_BIONIC_TSD_SLOTS) return 22; /* EINVAL */")
lines.append("    sober_bionic_tsd[key] = (void *)value;")
lines.append("    return 0;")
lines.append("}")
lines.append("")
lines.append("__attribute__((visibility(\"default\")))")
lines.append("void *pthread_getspecific(unsigned int key)")
lines.append("{")
lines.append("    if (key >= SOBER_BIONIC_TSD_SLOTS) return NULL;")
lines.append("    return sober_bionic_tsd[key];")
lines.append("}")
lines.append("")

# Data symbols need to be exported under their real names too.
for s in objs:
    n = cident(s["name"])
    lines.append(f"#define OBJALIAS(name) __asm__(\".globl \" #name \"\\n\\t\" #name \" = sober_libc_obj_\" #name)")
    break
lines.append("")

lines.append("void sober_bionic_libc_install(void)")
lines.append("{")
lines.append("    init_real_resolver();")
lines.append('    g_glibc = real_dlopen_fn')
lines.append('        ? real_dlopen_fn("libc.so.6", RTLD_LAZY | RTLD_LOCAL)')
lines.append('        : dlopen("libc.so.6", RTLD_LAZY | RTLD_LOCAL);')
for s in funcs:
    n = cident(s["name"])
    lines.append(f'    sober_libc_fn_{n} = native_lookup("{s["name"]}");')
# Override the sysconf slot with a wrapper that maps Bionic's page-size key.
lines.append("    real_sysconf_fn = (long (*)(int))sober_libc_fn_sysconf;")
lines.append("    sober_libc_fn_sysconf = (void *)sober_native_sysconf;")
for s in objs:
    n = cident(s["name"])
    lines.append(f'    {{ void *p = native_lookup("{s["name"]}");')
    lines.append(f'      if (p) __builtin_memcpy(sober_libc_obj_{n}, p, 16); }}')
# Host stream targets for the Bionic stdio translation above.  The object
# seeding just copied glibc's stdin/stdout/stderr pointers into our objects.
lines.append("    sober_host_stdin = *(FILE **)sober_libc_obj_stdin;")
lines.append("    sober_host_stdout = *(FILE **)sober_libc_obj_stdout;")
lines.append("    sober_host_stderr = *(FILE **)sober_libc_obj_stderr;")
lines.append("}")
lines.append("")
lines.append("const char *sober_bionic_libc_backend(void)")
lines.append("{")
lines.append('    return g_glibc ? "native glibc + Bionic version nodes" : "glibc unavailable";')
lines.append("}")
lines.append("unsigned sober_bionic_libc_symbol_count(void) { return %du; }" % len(symbols))
lines.append("")
lines.append("/* Self-initialising: the guest may call these symbols as soon as it is")
lines.append(" * mapped, so resolve glibc targets from a loader constructor. */")
lines.append("__attribute__((constructor)) static void sober_bionic_libc_ctor(void)")
lines.append("{")
lines.append("    sober_bionic_libc_install();")
lines.append("}")
lines.append("")
lines.append("void sober_bionic_libc_trampolines(void)")
lines.append("{")
# asm must be inside a function body; emit TRAMP for each function symbol
for s in funcs:
    if s["name"] in ("pthread_getspecific", "pthread_setspecific"):
        continue  # implemented above with Bionic TSD semantics
    if s["name"] in ("fflush", "fclose", "fwrite"):
        continue  # implemented above with Bionic __sF -> host stream mapping
    if s["name"] in ("sigaction", "sigemptyset", "sigfillset",
                     "pthread_sigmask"):
        continue  # implemented in bionic_signal.c with the Bionic ABI
    lines.append(f"    TRAMP({cident(s['name'])});")
lines.append("}")
lines.append("")

# Data aliases: one asm block per object symbol
for s in objs:
    n = cident(s["name"])
    lines.append(f'__asm__(".globl {n}\\n\\t{n} = sober_libc_obj_{n}");')

(ROOT / "src/compat/bionic_libc.c").write_text("\n".join(lines))

# Linker version script: assign each symbol to its required Bionic node.
ver = {v: [] for v in ("LIBC", "LIBC_N", "LIBC_O")}
for s in symbols:
    ver[s["version"]].append(s["name"])
mlines = ["/* GENERATED by gen_bionic_libc.py — Bionic version nodes. */"]
for node in ("LIBC", "LIBC_N", "LIBC_O"):
    mlines.append(f"{node} {{")
    mlines.append("  global:")
    if node == "LIBC":
        mlines.append("    sober_bionic_sf_full_install;")
    for n in ver[node]:
        mlines.append(f"    {n};")
    mlines.append("  local: *;")
    mlines.append("};")
(ROOT / "src/compat/bionic_libc.map").write_text("\n".join(mlines) + "\n")
print(f"generated {len(funcs)} function trampolines, {len(objs)} data symbols")
